// write.js <out.xlsx>: a workbook written by xljs, for Excel to open
// (only functions Excel 2021 has: LAMBDA, TAKE... are Microsoft 365's)
const [out] = xljs.args;
const book = workbooks.create();
const s = book.addSheet("値");
s.setValue("A1", 123.456);
s.setValue("A2", -0.000001);
s.setValue("A3", 1e20);
s.setValue("A4", "日本語の文字列");
s.setValue("A5", "改行を\n含む");
s.setValue("A6", true);
s.setValue("A7", false);
s.setValue("A8", new Date(2026, 3, 1));
s.setValue("A9", new Date(2026, 3, 1, 9, 30, 15));
s.setValue("A10", "00123");
s.setValue("A11", "=これは文字列");
s.setValue("A12", "𠮷野家 🍣 <&>\"'");
s.setValue("A13", 12345678901234567890);
s.setValue("A14", "  前後に空白  ");
s.setValue("A15", "_x000D_ そのまま");
s.setValue("A16", "\t制御\u0001文字");
s.write([["品名", "数量", "単価", "日付"], ["りんご", 3, 120, new Date(2026, 0, 5)], ["みかん", 5, 80, new Date(2026, 1, 10)], ["ぶどう", 1, 600, new Date(2026, 2, 15)]], { start: "C1", table: true });

const f = book.addSheet("数式");
for (let i = 1; i <= 10; i++) f.setValue(i, 1, i * 10);
f.cell("B1").formula = "=SUM(A1:A10)";
f.cell("B2").formula = "=XLOOKUP(50,A1:A10,A1:A10*2)";
f.cell("B3").formula = "=TEXTJOIN(\",\",TRUE,A1:A3)";
f.cell("B4").formula = "=LET(x,A1,y,A2,x*y)";
f.cell("B5").formula = "=MAXIFS(A1:A10,A1:A10,\"<70\")";
f.cell("B6").formula = "=IFS(A1>5,\"大\",TRUE,\"小\")";
f.cell("C1").formula = "=SEQUENCE(3,2)";
f.cell("E1").formula = "=FILTER(A1:A10,A1:A10>70)";
f.cell("F1").formula = "=SUM(E1#)";
f.cell("F2").formula = "=SORT(A1:A3,,-1)";
f.cell("G1").formula = "=@A1:A10";
f.cell("G2").formula = "=A1:A3*2";
f.cell("G5").formula = "=値!A1*2";
f.cell("G6").formula = "=値!A4&\"です\"";
f.cell("G7").formula = "=SWITCH(A1,10,\"十\",\"他\")";
f.cell("G8").formula = "=TEXT(DATE(2026,4,1),\"ggge年m月d日\")";
f.cell("G9").formula = "=UNIQUE({1;1;2})";
f.cell("G12").formula = "=IFERROR(1/0,\"エラー\")";
f.cell("G13").formula = "=1/0";
f.cell("G14").formula = "=CONCAT(\"a\",\"b\")&NUMBERVALUE(\"1.5\")";
f.cell("G15").formula = "=SORTBY(A1:A2,A1:A2,-1)";
f.cell("H1").formula = "=SUM(C1#)";
book.calculate();

const st = book.addSheet("書式");
st.setValue("A1", "結合");
st.merge("A1:C2");
st.setValue("A4", "太字赤");
st.cell("A4").style({ bold: true, color: "#FF0000", fontSize: 14, fontName: "メイリオ" });
st.setValue("B4", "塗り");
st.cell("B4").style({ background: "#DDEBF7", align: "center", valign: "middle", wrap: true });
st.setValue("C4", "罫線");
st.style("C4:D6", { border: "thin" });
st.style("C4", { border: { bottom: { style: "double", color: "#0000FF" } } });
st.setValue("A5", 1234.5);
st.cell("A5").style({ format: "#,##0" });
st.setValue("A6", 0.256);
st.cell("A6").style({ format: "0.0%" });
st.setValue("A7", new Date(2026, 3, 1));
st.cell("A7").style({ format: "ggge\"年\"m\"月\"d\"日\"" });
st.setValue("A8", 1.5);
st.cell("A8").style({ format: "[h]:mm" });
st.setValue("A9", 12345);
st.cell("A9").style({ format: "[DBNum1]G/標準" });
st.setValue("A10", new Date(2026, 3, 1));
st.cell("A10").style({ format: "aaaa" });
st.setColumnWidth("E", 30);
st.setRowHeight(8, 40);
st.freeze("B2");
st.autoFilter("A12:B14");
st.setValue("A12", "見出し"); st.setValue("B12", "値");
st.setValue("A13", "a"); st.setValue("B13", 1);
st.setValue("A14", "b"); st.setValue("B14", 2);
book.save(out);
