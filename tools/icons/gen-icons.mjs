// Writes src/ui/web/icons.css: the built-in pages' own icons (Lucide line
// icons) as CSS masks, so they are drawn as SVG in the text color.
// Usage: node tools/icons/gen-icons.mjs <lucide-static package dir>
// (npm pack lucide-static@<version> && tar xzf lucide-static-*.tgz → package/)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Lucide icon name → filled (the shape is painted, not just outlined).
const ICONS = {
  "arrow-left": false, "arrow-right": false, bug: false, check: false,
  "chevron-down": false, "chevron-right": false, "circle-check": false, "circle-x": false,
  clipboard: false, code: false, eraser: false, eye: false, file: false, "file-code": false,
  "file-spreadsheet": false, folder: false, "folder-open": false, "git-compare": false,
  "grip-vertical": false, history: false, house: false, info: false, "layout-grid": false,
  "messages-square": false, play: true, plus: false, "rotate-cw": false, save: false,
  square: true, table: false, terminal: false, "text-align-start": false,
  "triangle-alert": false, "wand-sparkles": false, x: false,
};

const pkg = process.argv[2];
if (!pkg) throw new Error("usage: node gen-icons.mjs <lucide-static package dir>");
const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;
let css = `/* Generated by tools/icons/gen-icons.mjs from lucide-static ${version} (ISC,
   vendor/lucide/LICENSE). Use: <i class="ic ic-play"></i>. */
.ic {
  display: inline-block; flex: none; width: 1.2em; height: 1.2em; vertical-align: -.25em;
  background-color: currentColor;
  -webkit-mask: var(--ic) center / contain no-repeat; mask: var(--ic) center / contain no-repeat;
}
`;
for (const [name, filled] of Object.entries(ICONS)) {
  let svg = readFileSync(join(pkg, "icons", name + ".svg"), "utf8")
    .replace(/<!--[\s\S]*?-->/, "")
    .replace(/\s*class="[^"]*"/, "")
    .replace(/\s*(width|height)="24"/g, "")
    .replace(/currentColor/g, "black")
    .replace(/\s+/g, " ").replace(/> </g, "><").replace(/ \/>/g, "/>").trim();
  if (filled) svg = svg.replace('fill="none"', 'fill="black"');
  const uri = svg.replace(/"/g, "'").replace(/[<>#%\n]/g, encodeURIComponent);
  css += `.ic-${name} { --ic: url("data:image/svg+xml,${uri}"); }\n`;
}
writeFileSync(new URL("../../src/ui/web/icons.css", import.meta.url), css);
